#ifndef PARSING_H
#define PARSING_H

#include <QObject>
#include "database.h"

///
/// \brief The CommandParsing class Класс для парсинга команд, полученных от клиентов
///
/// Преобразует текстовые команды в вызовы соответствующих методов базы данных.
/// Поддерживаемые команды:
/// - auth <login> <pass> — авторизация пользователя
/// - reg <login> <pass> <email> — регистрация пользователя
/// - stata <login> — получение статистики задач пользователя
/// - task1, task2, task3, task4 — получение текста соответствующей задачи
/// - submit <1:ответ> <2:ответ> <3:ответ> <4:ответ> <login> — проверка и сохранение ответов
///
class CommandParsing : public QObject {
    Q_OBJECT

private:
    ///
    /// \brief my_database Указатель на объект базы данных (синглтон)
    ///
    /// Используется для вызова методов работы с БД из класса CommandParsing.
    /// Инициализируется в конструкторе через Database::getInstance().
    /// \note Указатель не требует ручного удаления — объект управляется синглтоном.
    ///
    Database* my_database;

public:
    ///
    /// \brief Конструктор класса CommandParsing
    /// \param parent Родительский объект (для автоматического управления памятью)
    ///
    explicit CommandParsing(QObject *parent = nullptr);

    ///
    /// \brief Обрабатывает входящую команду и возвращает результат
    ///
    /// Метод разбивает строку на части, определяет команду и аргументы,
    /// вызывает соответствующий метод базы данных,
    /// формирует ответ для отправки клиенту.
    ///
    /// \param command Входная строка с командой и аргументами
    /// \return Строка с результатом обработки (ответ клиенту)
    ///
    QString Command(const QString &command);

    ///
    /// \brief Обрабатывает команду submit — проверяет ответы на задачи
    ///
    /// Формат входных данных: submit 1:ответ 2:ответ 3:ответ 4:ответ логин
    /// Для каждой задачи вычисляется правильный ответ через calculateShortestPath(),
    /// результат сохраняется в БД методом saveTaskResult().
    ///
    /// \param parts Разобранная команда (части строки)
    /// \param login Логин пользователя
    /// \return Пустая строка (ответ не требуется клиенту)
    ///
    QString handleSubmit(QStringList& parts, QString login);
};

#endif